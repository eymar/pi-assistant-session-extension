import { existsSync, unlinkSync } from "node:fs";
import { SessionManager, type ExtensionCommandContext } from "@earendil-works/pi-coding-agent";
import { copyProjection } from "./context.ts";
import { fileChangeReport, snapshotFiles, type FileChangeReport } from "./files.ts";
import { modelName, selectAssistantModel, type ModelRef } from "./models.ts";
import { findMarker, FLOWBACK, MARKER, type AssistantSessionMarker } from "./state.ts";
import { collectReviewedNote, type ReviewedNote } from "./summary.ts";

const STINT_BOUNDARY_MESSAGE =
  "[Assistant stint begins here]\n" +
  "Everything above is inherited primary-session context. " +
  "Only subsequent exchanges belong to this assistant stint. Wait for the next user request.";

interface FlowbackSource {
  assistantSessionId: string;
  assistantSessionFile: string | undefined;
  selectedModel: string;
  summaryModel: string | undefined;
}

/** Build the custom message appended to the primary session when returning from an assistant stint. */
function buildFlowbackMessage(
  source: FlowbackSource,
  reviewed: ReviewedNote,
  report: FileChangeReport,
) {
  const headerLines = [
    `[From the assistant session; selected model: ${source.selectedModel}]`,
    `Session: ${source.assistantSessionId}`,
  ];
  if (reviewed.summaryModel) {
    headerLines.push(`Summary generated by: ${reviewed.summaryModel}`);
  }

  const bodySections = [headerLines.join("\n")];
  if (reviewed.note) {
    bodySections.push(reviewed.note);
  }
  bodySections.push(report.text);

  return {
    customType: FLOWBACK,
    content: bodySections.join("\n\n"),
    display: true,
    details: {
      ...source,
      changed: report.changed,
      note: reviewed.note,
    },
  };
}

/**
 * Create and populate the assistant session file on disk before switching to it,
 * so the new runtime loads the projected context and selected model immediately.
 */
function prepareAssistantSession(
  ctx: ExtensionCommandContext,
  marker: AssistantSessionMarker,
  targetModel: ModelRef,
): string {
  const sm = SessionManager.create(ctx.cwd, ctx.sessionManager.getSessionDir(), {
    parentSession: marker.primaryPath,
  });

  copyProjection(sm, ctx.sessionManager.buildSessionProjection());

  marker.boundaryId = sm.appendMessage({
    role: "user",
    timestamp: Date.now(),
    content: STINT_BOUNDARY_MESSAGE,
  });

  sm.appendCustomEntry(MARKER, marker);
  sm.appendModelChange(targetModel.provider, targetModel.id);
  sm.appendSessionInfo(`assistant — ${marker.primaryName ?? "primary"}`);

  return sm.getSessionFile()!;
}

export async function returnToPrimary(ctx: ExtensionCommandContext): Promise<void> {
  await ctx.waitForIdle();

  const marker = findMarker(ctx.sessionManager.getBranch());
  if (!marker) {
    ctx.ui.notify("Not in an assistant session — nothing to return to.", "warning");
    return;
  }
  if (!existsSync(marker.primaryPath)) {
    ctx.ui.notify(`Primary session file no longer exists: ${marker.primaryPath}`, "error");
    return;
  }

  const reviewed = await collectReviewedNote(ctx, marker.boundaryId);

  // Snapshot files after summary review so any changes made during review are included.
  const currentSnapshot = await snapshotFiles(ctx.cwd);
  const report = fileChangeReport(marker.files, currentSnapshot);

  const source: FlowbackSource = {
    assistantSessionId: ctx.sessionManager.getSessionId(),
    assistantSessionFile: ctx.sessionManager.getSessionFile(),
    selectedModel: modelName(ctx.model),
    summaryModel: reviewed.summaryModel,
  };
  const flowbackMessage = buildFlowbackMessage(source, reviewed, report);

  const result = await ctx.switchSession(marker.primaryPath, {
    withSession: async (newCtx) => {
      // Use newCtx because the previous session context is stale after switching.
      await newCtx.sendMessage(flowbackMessage);
      newCtx.ui.notify("Back in the primary session.", "info");
    },
  });

  if (result.cancelled) {
    ctx.ui.notify("Switch cancelled; no flow-back was appended.", "warning");
  }
}

export async function openAssistant(ctx: ExtensionCommandContext): Promise<void> {
  await ctx.waitForIdle();

  // Running /assistant inside an assistant session toggles back to the primary session.
  if (findMarker(ctx.sessionManager.getBranch())) {
    return returnToPrimary(ctx);
  }

  const primaryPath = ctx.sessionManager.getSessionFile();
  if (!primaryPath || !existsSync(primaryPath)) {
    ctx.ui.notify("Send a message first — the primary session is not persisted yet.", "warning");
    return;
  }

  const selectedModel = await selectAssistantModel(ctx);
  if (!selectedModel) return;

  // Copy plain model identifiers so we do not hold onto objects from the old runtime after switching.
  const targetModel: ModelRef = { provider: selectedModel.provider, id: selectedModel.id };
  const targetModelName = modelName(targetModel);

  const marker: AssistantSessionMarker = {
    primaryPath,
    primaryName: ctx.sessionManager.getSessionName(),
    primaryLeafId: ctx.sessionManager.getLeafId(),
    createdAt: new Date().toISOString(),
    model: targetModelName,
    files: await snapshotFiles(ctx.cwd),
  };

  const assistantPath = prepareAssistantSession(ctx, marker, targetModel);

  const result = await ctx.switchSession(assistantPath, {
    withSession: async (newCtx) => {
      const actualModelName = modelName(newCtx.model);
      if (actualModelName !== targetModelName) {
        newCtx.ui.notify(
          `Assistant model restoration failed: expected ${targetModelName}, got ${actualModelName}. Returning to primary.`,
          "error",
        );
        await newCtx.switchSession(primaryPath);
        return;
      }
      newCtx.ui.notify(`⚡ Assistant session on ${actualModelName} — /primary to return.`, "info");
    },
  });

  if (result.cancelled) {
    unlinkSync(assistantPath);
    ctx.ui.notify("Assistant session switch cancelled; prepared session removed.", "warning");
  }
}
