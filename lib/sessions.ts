import { existsSync, unlinkSync } from "node:fs";
import { SessionManager, type ExtensionCommandContext } from "@earendil-works/pi-coding-agent";
import { copyProjection } from "./context.ts";
import { fileChangeReport, snapshotFiles } from "./files.ts";
import { modelName, selectAssistantModel } from "./models.ts";
import { findMarker, FLOWBACK, MARKER, type AssistantSessionMarker } from "./state.ts";
import { collectReviewedNote } from "./summary.ts";

export async function returnToPrimary(ctx: ExtensionCommandContext): Promise<void> {
  await ctx.waitForIdle();
  const marker = findMarker(ctx.sessionManager.getBranch());
  if (!marker) {
    ctx.ui.notify("Not in an assistant session — nothing to return to.", "warning");
    return;
  }
  if (!existsSync(marker.primaryPath)) {
    ctx.ui.notify(`Primary session file no longer exists: ${marker.primaryPath}`, "error");
    return;
  }

  const { note, summaryModel } = await collectReviewedNote(ctx, marker.boundaryId);
  // Snapshot last, after summary/review. Unavailable reporting is never silently
  // interpreted as no edits. Always pass the coverage information to the primary.
  const report = fileChangeReport(marker.files, await snapshotFiles(ctx.cwd));
  const source = {
    assistantSessionId: ctx.sessionManager.getSessionId(),
    assistantSessionFile: ctx.sessionManager.getSessionFile(),
    selectedModel: modelName(ctx.model),
    summaryModel,
  };
  const content = `[From the assistant session; selected model: ${source.selectedModel}]\n` +
    `Session: ${source.assistantSessionId}` + (summaryModel ? `\nSummary generated by: ${summaryModel}` : "") +
    `\n\n${note ? note + "\n\n" : ""}${report.text}`;
  const result = await ctx.switchSession(marker.primaryPath, {
    withSession: async (newCtx) => {
      // Commit only after success, using the fresh runtime. Do not capture old pi.
      await newCtx.sendMessage({ customType: FLOWBACK, content, display: true, details: { ...source, changed: report.changed, note } });
      newCtx.ui.notify("Back in the primary session.", "info");
    },
  });
  if (result.cancelled) ctx.ui.notify("Switch cancelled; no flow-back was appended.", "warning");
}

export async function openAssistant(ctx: ExtensionCommandContext): Promise<void> {
  await ctx.waitForIdle();
  if (findMarker(ctx.sessionManager.getBranch())) return returnToPrimary(ctx);

  const primaryPath = ctx.sessionManager.getSessionFile();
  if (!primaryPath || !existsSync(primaryPath)) {
    ctx.ui.notify("Send a message first — the primary session is not persisted yet.", "warning");
    return;
  }
  const selected = await selectAssistantModel(ctx);
  if (!selected) return;
  // Capture plain data only: runtime objects become stale after switching.
  const target = { provider: selected.provider, id: selected.id };
  const primaryName = ctx.sessionManager.getSessionName();
  const marker: AssistantSessionMarker = {
    primaryPath, primaryName, primaryLeafId: ctx.sessionManager.getLeafId(),
    createdAt: new Date().toISOString(), model: modelName(target), files: await snapshotFiles(ctx.cwd),
  };
  const assistantPath = prepareAssistantSession(ctx, marker, target);
  const result = await ctx.switchSession(assistantPath, {
    withSession: async (newCtx) => {
      if (modelName(newCtx.model) !== modelName(target)) {
        newCtx.ui.notify(`Assistant model restoration failed: expected ${modelName(target)}, got ${modelName(newCtx.model)}. Returning to primary.`, "error");
        await newCtx.switchSession(primaryPath);
        return;
      }
      newCtx.ui.notify(`⚡ Assistant session on ${modelName(newCtx.model)} — /primary to return.`, "info");
    },
  });
  if (result.cancelled) {
    unlinkSync(assistantPath);
    ctx.ui.notify("Assistant session switch cancelled; prepared session removed.", "warning");
  }
}

/** Prepare before runtime creation so model restoration sees the selection. */
function prepareAssistantSession(
  ctx: ExtensionCommandContext,
  marker: AssistantSessionMarker,
  target: { provider: string; id: string },
): string {
  const sm = SessionManager.create(ctx.cwd, ctx.sessionManager.getSessionDir(), { parentSession: marker.primaryPath });
  copyProjection(sm, ctx.sessionManager.buildSessionProjection());
  marker.boundaryId = sm.appendMessage({
    role: "user", timestamp: Date.now(),
    content: "[Assistant stint begins here]\nEverything above is inherited primary-session context. " +
      "Only subsequent exchanges belong to this assistant stint. Wait for the next user request.",
  });
  sm.appendCustomEntry(MARKER, marker);
  sm.appendModelChange(target.provider, target.id);
  sm.appendSessionInfo(`assistant — ${marker.primaryName ?? "primary"}`);
  return sm.getSessionFile()!;
}
